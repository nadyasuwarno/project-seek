"""Synthetic demo archive, clearly labeled as synthetic.

Real contributed microscopy should replace these. They exist so the full
pipeline (track -> signature -> compare -> credit) can be exercised on day one,
and so the comparison logic can be sanity-checked against systems whose
dynamics we control exactly:

  brownian          random walk (diffusive, alpha ~ 1)
  run_tumble        persistent swimmers with random reorientation (micro scale)
  walkers_macro     the same run-and-tumble dynamics at ~100x the spatial scale
  flock             Vicsek-style alignment (high collective alignment)
  oscillators       units moving back and forth on a fixed rhythm (periodic)
  clusters          units held in a few traps (confined, clustered)
  perturbed         swimmers that speed up after a perturbation, then recover

`run_tumble` vs `walkers_macro` is the key test: identical dynamics at very
different scales should score as highly similar in scale-free mode.
"""

