def _reflect(p: np.ndarray, v: np.ndarray | None = None):
    lo, hi = PAD, SIZE - PAD
    for axis in range(2):
        below, above = p[:, axis] < lo, p[:, axis] > hi
        p[below, axis] = 2 * lo - p[below, axis]
        p[above, axis] = 2 * hi - p[above, axis]
        if v is not None:
            v[below | above, axis] *= -1
    return p, v


def simulate(key: str, n: int = 32, frames: int = 128, seed: int = 0) -> np.ndarray:
    """Return positions (frames, n, 2) in pixels."""
    rng = np.random.default_rng(seed)
    pos = rng.uniform(PAD + 20, SIZE - PAD - 20, (n, 2))
    out = np.zeros((frames, n, 2))

    if key == "brownian":
        for t in range(frames):
            out[t] = pos
            pos, _ = _reflect(pos + rng.normal(0, 1.3, (n, 2)))

    elif key in ("run_tumble", "walkers_macro", "perturbed"):
        heading = rng.uniform(0, 2 * np.pi, n)
        for t in range(frames):
            out[t] = pos
            speed = 2.5
            if key == "perturbed":
                speed = 1.2 if t < 60 else 1.2 + 2.6 * np.exp(-(t - 60) / 8.0)
            tumble = rng.random(n) < 0.05
            heading[tumble] = rng.uniform(0, 2 * np.pi, tumble.sum())
            heading += rng.normal(0, 0.08, n)
            v = speed * np.stack([np.cos(heading), np.sin(heading)], axis=1)
            pos, v = _reflect(pos + v + rng.normal(0, 0.15, (n, 2)), v)
            heading = np.arctan2(v[:, 1], v[:, 0])

    elif key == "flock":
        heading = rng.uniform(-0.4, 0.4, n)
        for t in range(frames):
            out[t] = pos
            d = np.linalg.norm(pos[:, None] - pos[None], axis=2)
            neigh = d < 40
            mean_dir = np.angle((neigh * np.exp(1j * heading)[None]).sum(axis=1))
            heading = mean_dir + rng.normal(0, 0.15, n)
            v = 2.2 * np.stack([np.cos(heading), np.sin(heading)], axis=1)
            pos, v = _reflect(pos + v, v)
            heading = np.arctan2(v[:, 1], v[:, 0])

    elif key == "oscillators":
        centre = pos.copy()
        axis_angle = rng.uniform(0, np.pi, n)
        axis = np.stack([np.cos(axis_angle), np.sin(axis_angle)], axis=1)
        phase = rng.uniform(0, 2 * np.pi, n)
        for t in range(frames):
            out[t] = centre + 7 * np.sin(2 * np.pi * t / 16 + phase)[:, None] * axis + rng.normal(0, 0.2, (n, 2))

    elif key == "clusters":
        centres = rng.uniform(PAD + 40, SIZE - PAD - 40, (5, 2))
        home = centres[rng.integers(0, 5, n)] + rng.normal(0, 9, (n, 2))
        pos = home.copy()
        for t in range(frames):
            out[t] = pos
            pos = pos + 0.25 * (home - pos) + rng.normal(0, 1.2, (n, 2))
    else:
        raise ValueError(f"Unknown demo system: {key}")
    return out


def render_video(positions: np.ndarray, path: Path, seed: int = 0, sigma: float = 1.8) -> Path:
    """Render bright Gaussian blobs on a noisy dark background as browser-playable WebM."""
    rng = np.random.default_rng(seed + 1)
    path = Path(path).with_suffix(".webm")
    path.parent.mkdir(parents=True, exist_ok=True)
    writer = cv2.VideoWriter(str(path), cv2.VideoWriter_fourcc(*"VP80"), 10, (SIZE, SIZE))
    r = int(4 * sigma)
    yy, xx = np.mgrid[-r:r + 1, -r:r + 1]
    for frame_pos in positions:
        img = np.full((SIZE, SIZE), 18.0) + rng.normal(0, 4, (SIZE, SIZE))
        for x, y in frame_pos:
            cx, cy = int(round(x)), int(round(y))
            if r <= cx < SIZE - r and r <= cy < SIZE - r:
                blob = 210 * np.exp(-((xx - (x - cx)) ** 2 + (yy - (y - cy)) ** 2) / (2 * sigma ** 2))
                img[cy - r:cy + r + 1, cx - r:cx + r + 1] += blob
        frame = np.clip(img, 0, 255).astype(np.uint8)
        writer.write(cv2.cvtColor(frame, cv2.COLOR_GRAY2BGR))
    writer.release()
    return path
